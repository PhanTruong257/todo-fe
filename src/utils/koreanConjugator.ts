export function findConjugation(query: string): VerbConjugation | undefined {
  const clean = query.trim().replace(/\s+/g, '');
  return VERB_CONJUGATION_DATABASE.find(
    (v) =>
      v.root === clean ||
      v.presentCasual === clean ||
      v.meaningVi.toLowerCase().includes(query.toLowerCase()),
  );
}
